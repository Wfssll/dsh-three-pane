import { readFile, mkdir, writeFile, copyFile } from 'node:fs/promises';
const read = path => readFile(new URL(`../${path}`, import.meta.url), 'utf8');
await mkdir(new URL('../lib/', import.meta.url), { recursive: true });
const model = (await read('src/model.js')).replace(/^export /gm, '');
const client = (await read('src/client.js')).replace(/^import .*;\n/gm, '').replace(/^export /gm, '');
const css = await read('src/style.css');
await writeFile(new URL('../lib/client.js', import.meta.url),
  `// Generated by scripts/build.mjs. React comes from the DSH module table.\nwindow.__ModuleLoader__.load({\n id: 'dsh-three-pane',\n factory(require) {\n const React = require('react');\n const { createPortal } = require('react-dom');\n const CSS = ${JSON.stringify(css)};\n${model}\n${client}\n return { name, inject, apply };\n }\n});\n`);
await copyFile(new URL('../src/index.js', import.meta.url), new URL('../lib/index.js', import.meta.url));
console.log('Built lib/client.js and lib/index.js');
